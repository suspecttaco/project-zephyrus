import type { Account } from "../../domain/entities/account.js";
import { Movement } from "../../domain/entities/movement.js";
import { MovementType } from "../../domain/enums.js";
import type { MovementCategory } from "../../domain/enums.js";
import { BusinessConflictError, NotFoundError } from "../../domain/errors.js";
import type { IAccountRepository } from "../../domain/repositories/account-repository.js";
import type { IMovementRepository } from "../../domain/repositories/movement-repository.js";
import { requireOwnedAccount } from "../require-owned-account.js";
import type { RequestContext } from "../request-context.js";

export interface MovementEditInput {
    amountInCents: number;
    type: MovementType;
    accountId: string;
    destinationAccountId?: string | null;
    date: Date;
    category?: MovementCategory | null;
    description: string;
}

export class UpdateMovement {
    constructor(
        private readonly movementRepository: IMovementRepository,
        private readonly accountRepository: IAccountRepository,
    ) {}

    async execute(input: {
        accountId: string;
        movementId: string;
        context: RequestContext;
        edit: MovementEditInput;
    }): Promise<Movement> {
        const movement = await this.movementRepository.findById(input.movementId);
        if (!movement) {
            throw new NotFoundError("movement not found");
        }

        if (movement.accountId !== input.accountId) {
            throw new NotFoundError("movement not found in this account");
        }

        const oldSource = await requireOwnedAccount(
            this.accountRepository,
            movement.accountId,
            input.context.ownerUserId,
        );

        if (movement.installmentPurchaseId !== null) {
            throw new BusinessConflictError("movements generated by an installment purchase are not editable");
        }

        const updated = Movement.create({
            id: movement.id,
            createdAt: movement.createdAt,
            accountId: input.edit.accountId,
            destinationAccountId: input.edit.destinationAccountId ?? null,
            type: input.edit.type,
            amountInCents: input.edit.amountInCents,
            category: input.edit.category ?? null,
            description: input.edit.description,
            date: input.edit.date,
        });

        const newSource = await requireOwnedAccount(
            this.accountRepository,
            updated.accountId,
            input.context.ownerUserId,
        );

        let newDestination: Account | null = null;
        if (updated.type === MovementType.TRANSFER && updated.destinationAccountId !== null) {
            newDestination = await requireOwnedAccount(
                this.accountRepository,
                updated.destinationAccountId,
                input.context.ownerUserId,
            );
        }

        const affected = new Map<string, Account>();
        const track = (account: Account): void => {
            affected.set(account.id, account.clone());
        };
        track(oldSource);
        if (movement.destinationAccountId !== null) {
            const oldDestination = await this.accountRepository.findById(movement.destinationAccountId);
            if (!oldDestination) {
                throw new NotFoundError("destination account not found");
            }
            track(oldDestination);
        }
        track(newSource);
        if (newDestination !== null) {
            track(newDestination);
        }

        const requireAccount = (id: string): Account => {
            const account = affected.get(id);
            if (!account) throw new NotFoundError("account not found");
            return account;
        };

        if (movement.type === MovementType.TRANSFER && movement.destinationAccountId !== null) {
            requireAccount(movement.accountId).transferIn(movement.amount);
            requireAccount(movement.destinationAccountId).transferOut(movement.amount);
        } else {
            requireAccount(movement.accountId).applyMovement(Movement.oppositeType(movement.type), movement.amount);
        }

        if (updated.type === MovementType.TRANSFER && updated.destinationAccountId !== null) {
            requireAccount(updated.accountId).transferOut(updated.amount);
            requireAccount(updated.destinationAccountId).transferIn(updated.amount);
        } else {
            requireAccount(updated.accountId).applyMovement(updated.type, updated.amount);
        }

        await this.movementRepository.save(updated);
        for (const account of affected.values()) {
            await this.accountRepository.save(account);
        }

        return updated;
    }
}
