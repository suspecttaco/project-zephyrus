import { Movement } from "../../domain/entities/movement.js";
import { BusinessConflictError, NotFoundError } from "../../domain/errors.js";
import type { IAccountRepository } from "../../domain/repositories/account-repository.js";
import type { IMovementRepository } from "../../domain/repositories/movement-repository.js";
import { requireOwnedAccount } from "../require-owned-account.js";
import type { RequestContext } from "../request-context.js";

export class DeleteMovement {
    constructor(
        private readonly movementRepository: IMovementRepository,
        private readonly accountRepository: IAccountRepository,
    ) {}

    async execute(input: { accountId: string; movementId: string; context: RequestContext }): Promise<void> {
        const movement = await this.movementRepository.findById(input.movementId);
        if (!movement) {
            throw new NotFoundError("movement not found");
        }

        if (movement.accountId !== input.accountId) {
            throw new NotFoundError("movement not found in this account");
        }

        const source = await requireOwnedAccount(this.accountRepository, movement.accountId, input.context.ownerUserId);

        if (movement.destinationAccountId !== null) {
            throw new BusinessConflictError("cannot delete a transfer movement: it has a destination account");
        }

        if (movement.installmentPurchaseId !== null) {
            throw new BusinessConflictError("cannot delete a movement generated by an installment purchase");
        }

        const workingCopy = source.clone();
        workingCopy.applyMovement(Movement.oppositeType(movement.type), movement.amount);

        await this.movementRepository.delete(movement.id);
        await this.accountRepository.save(workingCopy);
    }
}
